// Generates sharded Flutter test entrypoints under client/test/.generated/
// so `flutter test` compiles once per shard instead of once per test file.
//
// Usage (from client/):
//   dart run tool/test_shards.dart generate [--shards 4] [--timings <json>]
//   dart run tool/test_shards.dart clean
import 'dart:convert';
import 'dart:io';

const _defaultShards = 4;
const _generatedDir = 'test/.generated';
const _isolatedFile = 'test/isolated_tests.txt';

void main(List<String> args) {
  final cmd = args.isEmpty ? 'generate' : args.first;
  if (cmd == 'clean') {
    final dir = Directory(_generatedDir);
    if (dir.existsSync()) dir.deleteSync(recursive: true);
    return;
  }
  if (cmd != 'generate') {
    stderr.writeln(
      'Usage: dart run tool/test_shards.dart [generate|clean] [--shards N] [--timings path]',
    );
    exitCode = 2;
    return;
  }

  var shardCount = _defaultShards;
  String? timingsPath;
  for (var i = 1; i < args.length; i++) {
    if (args[i] == '--shards' && i + 1 < args.length) {
      shardCount = int.tryParse(args[++i]) ?? _defaultShards;
    } else if (args[i] == '--timings' && i + 1 < args.length) {
      timingsPath = args[++i];
    }
  }
  if (shardCount < 1) shardCount = 1;

  final isolated = _readIsolated();
  final timings = _readTimings(timingsPath);
  final files = _discoverTests(isolated);

  final outDir = Directory(_generatedDir);
  if (outDir.existsSync()) outDir.deleteSync(recursive: true);
  outDir.createSync(recursive: true);

  // Greedy LPT bin packing by previous duration (or equal weight 1000ms if unknown).
  final sorted = [...files]
    ..sort((a, b) {
      final tb = timings[b] ?? 1000;
      final ta = timings[a] ?? 1000;
      final cmp = tb.compareTo(ta);
      return cmp != 0 ? cmp : a.compareTo(b);
    });

  final buckets = List.generate(shardCount, (_) => <String>[]);
  final loads = List<int>.filled(shardCount, 0);
  for (final f in sorted) {
    var best = 0;
    for (var i = 1; i < shardCount; i++) {
      if (loads[i] < loads[best]) best = i;
    }
    buckets[best].add(f);
    loads[best] += timings[f] ?? 1000;
  }

  for (var i = 0; i < shardCount; i++) {
    final shardFiles = buckets[i]..sort();
    if (shardFiles.isEmpty) continue;
    final buf = StringBuffer()
      ..writeln('// GENERATED BY tool/test_shards.dart — DO NOT EDIT.')
      ..writeln("import 'package:flutter/foundation.dart';")
      ..writeln("import 'package:flutter/widgets.dart';")
      ..writeln("import 'package:flutter_test/flutter_test.dart';")
      ..writeln();
    for (var j = 0; j < shardFiles.length; j++) {
      // Files are relative to client/test/, and generated shards live in client/test/.generated/.
      final rel = shardFiles[j].startsWith('test/')
          ? shardFiles[j].substring(5)
          : shardFiles[j];
      buf.writeln("import '../$rel' as t$j;");
    }
    buf
      ..writeln()
      ..writeln('void _resetShardState() {')
      ..writeln('  debugDefaultTargetPlatformOverride = null;')
      ..writeln('  try {')
      ..writeln('    final b = WidgetsBinding.instance;')
      ..writeln('    if (b is TestWidgetsFlutterBinding) {')
      ..writeln('      b.platformDispatcher.views.first.resetPhysicalSize();')
      ..writeln(
        '      b.platformDispatcher.views.first.resetDevicePixelRatio();',
      )
      ..writeln(
        '      b.platformDispatcher.clearPlatformBrightnessTestValue();',
      )
      ..writeln('      b.platformDispatcher.clearTextScaleFactorTestValue();')
      ..writeln(
        '      b.platformDispatcher.clearAccessibilityFeaturesTestValue();',
      )
      ..writeln('    }')
      ..writeln('  } catch (_) {}')
      ..writeln('}')
      ..writeln()
      ..writeln('void main() {')
      ..writeln('  tearDown(_resetShardState);');
    for (var j = 0; j < shardFiles.length; j++) {
      final label = shardFiles[j].replaceAll("'", "\\'");
      buf.writeln("  group('$label', t$j.main);");
    }
    buf.writeln('}');
    File('$_generatedDir/shard_${i}_test.dart')
        .writeAsStringSync(buf.toString());
  }

  stdout.writeln(
    'Generated $shardCount shards for ${files.length} test files (${isolated.length} isolated).',
  );
}

Set<String> _readIsolated() {
  final f = File(_isolatedFile);
  if (!f.existsSync()) return {};
  final out = <String>{};
  for (final raw in f.readAsLinesSync()) {
    final line = raw.split('#').first.trim();
    if (line.isNotEmpty) out.add(line);
  }
  return out;
}

Map<String, int> _readTimings(String? path) {
  if (path == null) return {};
  final f = File(path);
  if (!f.existsSync()) return {};
  try {
    final decoded = jsonDecode(f.readAsStringSync());
    if (decoded is Map<String, dynamic>) {
      return {
        for (final e in decoded.entries)
          if (e.value is num) e.key: (e.value as num).round(),
      };
    }
  } catch (_) {}
  return {};
}

List<String> _discoverTests(Set<String> isolated) {
  final root = Directory('test');
  if (!root.existsSync()) return [];
  final out = <String>[];
  for (final entity in root.listSync(recursive: true, followLinks: false)) {
    if (entity is! File) continue;
    final p = entity.path.replaceAll('\\', '/');
    if (!p.endsWith('_test.dart')) continue;
    if (p.startsWith('test/.generated/')) continue;
    if (isolated.contains(p)) continue;
    out.add(p);
  }
  out.sort();
  return out;
}
